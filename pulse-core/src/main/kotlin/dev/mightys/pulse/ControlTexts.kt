    /** All keys and strings of one language; empty for an unknown language. */
    fun table(language: String): Map<String, String> = values[language]?.let { list -> keys.zip(list).toMap() }.orEmpty()

    /** One string of a language, or null. */
    fun text(language: String, key: String): String? = values[language]?.getOrNull(keys.indexOf(key))

    /**
     * The best built-in language for the preferred tags (app language first, then the system), falling back to English.
     * "pt" gives pt-BR, any "zh" gives zh-Hans and "sr" gives sr-Latn.
     */
    fun pick(tags: List<String>): String {
        for (raw in tags) {
            val tag = raw.replace('_', '-').trim()
            if (tag.isEmpty()) continue
            val lower = tag.lowercase(java.util.Locale.ROOT)
            languages.firstOrNull { it.lowercase(java.util.Locale.ROOT) == lower }?.let { return it }
            val primary = lower.substringBefore('-')
            when (primary) {
                "pt" -> return "pt-BR"
                "zh" -> return "zh-Hans"
                "sr" -> return "sr-Latn"
            }
            languages.firstOrNull { it.lowercase(java.util.Locale.ROOT) == primary }?.let { return it }
        }
        return "en"
    }
